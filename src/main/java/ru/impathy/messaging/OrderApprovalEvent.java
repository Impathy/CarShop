package ru.impathy.messaging;

import java.util.UUID;

public class OrderApprovalEvent {
    private UUID eventId;
    private UUID orderId;
    private OrderType orderType;
    private UUID clientId;
    private UUID managerId;
    private UUID carId;
    private UUID configuredCarId;
    private String traceId;

    public UUID getEventId() {
        return eventId;
    }

    public void setEventId(UUID eventId) {
        this.eventId = eventId;
    }

    public UUID getOrderId() {
        return orderId;
    }

    public void setOrderId(UUID orderId) {
        this.orderId = orderId;
    }

    public OrderType getOrderType() {
        return orderType;
    }

    public void setOrderType(OrderType orderType) {
        this.orderType = orderType;
    }

    public UUID getClientId() {
        return clientId;
    }

    public void setClientId(UUID clientId) {
        this.clientId = clientId;
    }

    public UUID getManagerId() {
        return managerId;
    }

    public void setManagerId(UUID managerId) {
        this.managerId = managerId;
    }

    public UUID getCarId() {
        return carId;
    }

    public void setCarId(UUID carId) {
        this.carId = carId;
    }

    public UUID getConfiguredCarId() {
        return configuredCarId;
    }

    public void setConfiguredCarId(UUID configuredCarId) {
        this.configuredCarId = configuredCarId;
    }

    public String getTraceId() {
        return traceId;
    }

    public void setTraceId(String traceId) {
        this.traceId = traceId;
    }
}
